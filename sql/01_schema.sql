-- Ecotourism database: revised PostgreSQL portfolio implementation.
-- Run this script inside an already-created database.
-- Tested by inspection for PostgreSQL syntax; execute locally to verify in your environment.

CREATE TABLE guide (
    guide_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    languages_spoken TEXT[] NOT NULL DEFAULT '{}',
    special_skills TEXT[] NOT NULL DEFAULT '{}',
    rating NUMERIC(3,2),
    CONSTRAINT guide_rating_range CHECK (rating IS NULL OR rating BETWEEN 0 AND 5)
);

CREATE TABLE destination (
    destination_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    location TEXT NOT NULL,
    climate VARCHAR(100),
    description TEXT
);

CREATE TABLE tourist (
    tourist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guide_id BIGINT REFERENCES guide(guide_id) ON DELETE SET NULL,
    name VARCHAR(255) NOT NULL,
    age INTEGER NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone_number VARCHAR(30),
    nationality VARCHAR(100) NOT NULL,
    travel_history TEXT[] NOT NULL DEFAULT '{}',
    preferences TEXT[] NOT NULL DEFAULT '{}',
    CONSTRAINT tourist_age_positive CHECK (age > 0)
);

CREATE TABLE activity (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    duration INTERVAL NOT NULL,
    difficulty_level VARCHAR(20) NOT NULL,
    best_time_to_visit VARCHAR(255),
    local_cuisine TEXT[] NOT NULL DEFAULT '{}',
    CONSTRAINT activity_duration_positive CHECK (duration > INTERVAL '0'),
    CONSTRAINT activity_difficulty_valid
        CHECK (difficulty_level IN ('Easy', 'Moderate', 'Challenging'))
);

CREATE TABLE accommodation (
    accommodation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT NOT NULL REFERENCES destination(destination_id) ON DELETE RESTRICT,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(30) NOT NULL,
    location TEXT NOT NULL,
    price_per_night NUMERIC(10,2) NOT NULL,
    equipment_needed TEXT[] NOT NULL DEFAULT '{}',
    age_limit INTEGER,
    CONSTRAINT accommodation_type_valid
        CHECK (type IN ('Hotel', 'Hostel', 'Camping Site', 'Other')),
    CONSTRAINT accommodation_price_nonnegative CHECK (price_per_night >= 0),
    CONSTRAINT accommodation_age_limit_nonnegative CHECK (age_limit IS NULL OR age_limit >= 0)
);

CREATE TABLE transportation (
    transportation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(30) NOT NULL,
    schedule TEXT,
    price NUMERIC(10,2) NOT NULL,
    capacity INTEGER NOT NULL,
    accessibility TEXT,
    CONSTRAINT transportation_type_valid
        CHECK (type IN ('Bus', 'Train', 'Plane', 'Other')),
    CONSTRAINT transportation_price_nonnegative CHECK (price >= 0),
    CONSTRAINT transportation_capacity_positive CHECK (capacity > 0)
);

CREATE TABLE reservation (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tourist_id BIGINT NOT NULL REFERENCES tourist(tourist_id) ON DELETE RESTRICT,
    activity_id BIGINT NOT NULL REFERENCES activity(activity_id) ON DELETE RESTRICT,
    accommodation_id BIGINT NOT NULL REFERENCES accommodation(accommodation_id) ON DELETE RESTRICT,
    transportation_id BIGINT NOT NULL REFERENCES transportation(transportation_id) ON DELETE RESTRICT,
    reservation_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    payment_status VARCHAR(20) NOT NULL DEFAULT 'Unpaid',
    total_cost NUMERIC(10,2) NOT NULL,
    special_requests TEXT,
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    CONSTRAINT reservation_status_valid
        CHECK (status IN ('Confirmed', 'Pending', 'Cancelled')),
    CONSTRAINT reservation_payment_status_valid
        CHECK (payment_status IN ('Paid', 'Unpaid')),
    CONSTRAINT reservation_total_cost_nonnegative CHECK (total_cost >= 0),
    CONSTRAINT reservation_dates_valid CHECK (check_out_date > check_in_date)
);

-- Many-to-many relationships from the requirements.
CREATE TABLE tourist_activity (
    tourist_id BIGINT NOT NULL REFERENCES tourist(tourist_id) ON DELETE CASCADE,
    activity_id BIGINT NOT NULL REFERENCES activity(activity_id) ON DELETE CASCADE,
    PRIMARY KEY (tourist_id, activity_id)
);

CREATE TABLE tourist_destination (
    tourist_id BIGINT NOT NULL REFERENCES tourist(tourist_id) ON DELETE CASCADE,
    destination_id BIGINT NOT NULL REFERENCES destination(destination_id) ON DELETE CASCADE,
    PRIMARY KEY (tourist_id, destination_id)
);

CREATE TABLE guide_destination (
    guide_id BIGINT NOT NULL REFERENCES guide(guide_id) ON DELETE CASCADE,
    destination_id BIGINT NOT NULL REFERENCES destination(destination_id) ON DELETE CASCADE,
    PRIMARY KEY (guide_id, destination_id)
);

CREATE TABLE activity_destination (
    activity_id BIGINT NOT NULL REFERENCES activity(activity_id) ON DELETE CASCADE,
    destination_id BIGINT NOT NULL REFERENCES destination(destination_id) ON DELETE CASCADE,
    PRIMARY KEY (activity_id, destination_id)
);

CREATE TABLE activity_guide (
    activity_id BIGINT NOT NULL REFERENCES activity(activity_id) ON DELETE CASCADE,
    guide_id BIGINT NOT NULL REFERENCES guide(guide_id) ON DELETE CASCADE,
    PRIMARY KEY (activity_id, guide_id)
);

CREATE TABLE guide_accommodation (
    guide_id BIGINT NOT NULL REFERENCES guide(guide_id) ON DELETE CASCADE,
    accommodation_id BIGINT NOT NULL REFERENCES accommodation(accommodation_id) ON DELETE CASCADE,
    PRIMARY KEY (guide_id, accommodation_id)
);

CREATE TABLE transportation_destination (
    transportation_id BIGINT NOT NULL REFERENCES transportation(transportation_id) ON DELETE CASCADE,
    destination_id BIGINT NOT NULL REFERENCES destination(destination_id) ON DELETE CASCADE,
    PRIMARY KEY (transportation_id, destination_id)
);

CREATE TABLE guide_transportation (
    guide_id BIGINT NOT NULL REFERENCES guide(guide_id) ON DELETE CASCADE,
    transportation_id BIGINT NOT NULL REFERENCES transportation(transportation_id) ON DELETE CASCADE,
    PRIMARY KEY (guide_id, transportation_id)
);

-- Helpful indexes for common foreign-key joins and date filtering.
CREATE INDEX idx_tourist_guide_id ON tourist(guide_id);
CREATE INDEX idx_reservation_tourist_id ON reservation(tourist_id);
CREATE INDEX idx_reservation_activity_id ON reservation(activity_id);
CREATE INDEX idx_reservation_accommodation_id ON reservation(accommodation_id);
CREATE INDEX idx_reservation_transportation_id ON reservation(transportation_id);
CREATE INDEX idx_reservation_check_in_date ON reservation(check_in_date);
